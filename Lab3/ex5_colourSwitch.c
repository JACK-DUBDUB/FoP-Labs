// Libraries
#include <stdio.h>

int main()
{
    char colour = 'Y';

    switch (colour)
    {
        case 'R':
            printf("Red\n");
        
        case 'B':
            printf("Blue\n");

        case 'Y':
            printf("Yellow\n");
    }
    return 0;
}